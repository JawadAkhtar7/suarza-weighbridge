/**
 * Bakes the slip's four font families into one TypeScript module.
 *
 *   node scripts/build-slip-fonts.mjs
 *
 * Only the server-rendered pages use this — the two Vite apps import
 * `fonts.css` and let the bundler emit the woff2 files properly. A page the
 * cloud renders to a string has no bundler, and the public QR page runs under a
 * CSP that allows no network fetches at all, so its faces have to travel inside
 * the markup. 400 kB once, for a page that is opened by a driver holding a
 * paper slip and then closed.
 */

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const req = createRequire(resolve(root, 'packages/ui/package.json'));

/** Exactly the faces layout.ts asks for. Each extra one is dead weight. */
const FACES = [
  ['montserrat', 'Montserrat', [500, 600, 700, 900], ['latin']],
  ['noto-naskh-arabic', 'Noto Naskh Arabic', [400, 600, 700], ['arabic']],
  ['archivo', 'Archivo', [500, 600], ['latin']],
  ['open-sans', 'Open Sans', [600, 700], ['latin']],
];

const rules = [];
let bytes = 0;
for (const [pkg, family, weights, subsets] of FACES) {
  for (const weight of weights) {
    for (const subset of subsets) {
      const file = req.resolve(`@fontsource/${pkg}/files/${pkg}-${subset}-${weight}-normal.woff2`);
      const data = readFileSync(file);
      bytes += data.byteLength;
      rules.push(
        `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};` +
          `src:url(data:font/woff2;base64,${data.toString('base64')}) format('woff2');` +
          `font-display:block}`,
      );
    }
  }
}

const out = `/**
 * The slip's fonts, inlined.
 *
 * GENERATED by scripts/build-slip-fonts.mjs. Do not edit by hand.
 * See that script for why a server-rendered slip carries its own faces.
 */

export const SLIP_FONT_CSS = ${JSON.stringify(rules.join('\n'))};
`;

writeFileSync(resolve(root, 'packages/ui/src/receipt/slip/fonts-inline.ts'), out);
console.log(`fonts-inline.ts: ${rules.length} faces, ${(bytes / 1024).toFixed(0)} kB -> ${(out.length / 1024).toFixed(0)} kB`);
