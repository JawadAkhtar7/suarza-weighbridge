/**
 * Turns the slip's artwork into one TypeScript module of data URIs.
 *
 *   node scripts/build-slip-art.mjs
 *
 * Why inline rather than serve the files:
 *
 * The same receipt markup is rendered in four places — the operator's print
 * page (Vite), the manager dashboard (Vite), the public QR page (server-side
 * rendered to an HTML string by the cloud API), and the browser's own
 * print-to-PDF. A relative `/assets/logo.svg` resolves differently in each of
 * those, and on the weighbridge PC the page has to work with no network at all.
 * A data URI has no such problem: it is part of the markup and cannot 404.
 *
 * Rerun this after replacing anything in `assets/`. The output is committed, so
 * nobody needs this script to build the project.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assetsDir = resolve(here, '../packages/ui/src/receipt/slip/assets');
const outFile = resolve(here, '../packages/ui/src/receipt/slip/art.ts');

const MIME = { '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.png': 'image/png' };

/** `icon-driver.svg` -> `ICON_DRIVER`. */
const constantName = (file) =>
  basename(file, extname(file)).replace(/[^a-z0-9]+/gi, '_').toUpperCase();

const files = readdirSync(assetsDir)
  .filter((file) => MIME[extname(file).toLowerCase()])
  .sort();

const lines = [
  '/**',
  ' * The slip artwork, inlined.',
  ' *',
  ' * GENERATED by scripts/build-slip-art.mjs from the files in ./assets.',
  ' * Edit those and rerun it; do not edit this file by hand.',
  ' *',
  ' * See the script for why these are data URIs rather than served files.',
  ' */',
  '',
];

let total = 0;
for (const file of files) {
  const bytes = readFileSync(join(assetsDir, file));
  total += bytes.byteLength;
  const uri = `data:${MIME[extname(file).toLowerCase()]};base64,${bytes.toString('base64')}`;
  lines.push(`/** ${file} — ${(bytes.byteLength / 1024).toFixed(1)} kB */`);
  lines.push(`export const ${constantName(file)} = '${uri}';`);
  lines.push('');
}

writeFileSync(outFile, lines.join('\n'));
console.log(
  `art.ts: ${files.length} files, ${(total / 1024).toFixed(0)} kB raw -> ${(
    Buffer.byteLength(lines.join('\n')) / 1024
  ).toFixed(0)} kB module`,
);
for (const file of files) console.log(`  ${constantName(file)}  <- ${file}`);
